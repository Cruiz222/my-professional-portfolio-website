// Generate real JavaScript imports for Vercel's Node runtime.
import ts from "typescript";
import {readFile, writeFile, mkdir} from "node:fs/promises";
const root = new URL("../",import.meta.url);
await mkdir(new URL("server/runtime/",root),{recursive:true});
for (const [source, destination] of [
 ["src/data/projects.ts","server/runtime/projects.mjs"],
 ["server/cloud.ts","server/runtime/cloud.mjs"],
]) {
 const text = await readFile(new URL(source,root),"utf8");
 const result = ts.transpileModule(text.replace('"../src/data/projects.ts"','"./projects.mjs"'),{
  compilerOptions:{target:ts.ScriptTarget.ES2023,module:ts.ModuleKind.ESNext},fileName:source,
 });
 if (/\bfrom\s*["'][^"']+\.ts["']/.test(result.outputText)) throw new Error(`Unresolved TypeScript runtime import in ${source}`);
 await writeFile(new URL(destination,root),"// Generated by scripts/build-server.mjs. Edit the TypeScript source.\n"+result.outputText);
}
await writeFile(new URL("server/runtime/cloud.d.mts",root),'// Type declarations for the generated runtime.\nexport * from "../cloud.ts";\n');
await writeFile(new URL("server/runtime/projects.d.mts",root),'// Type declarations for the generated runtime.\nexport * from "../../src/data/projects.ts";\n');
